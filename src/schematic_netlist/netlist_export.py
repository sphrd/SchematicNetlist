"""Flat netlist exports: a readable text netlist and a JSON document with the same content."""
from __future__ import annotations

import json
from dataclasses import asdict

from .circuit import Circuit


def write_text_netlist(circuit: Circuit, title: str) -> str:
    out = [
        f"# {title} -- flat netlist generated by SchematicNetlist from {circuit.source}",
        f"# {len(circuit.pages)} page(s), {len(circuit.parts)} parts, {len(circuit.nets)} nets",
        "#",
        "# PART <refdes> <kind> [value] page=<pages> pins=<n>",
        "# NET  <name> [rail] pins=<n>  then one line of <refdes>.<pin>[/<pin name>] per net",
        "",
    ]
    for p in circuit.parts:
        v = f" {p.value}" if p.value else ""
        out.append(f"PART {p.refdes} {p.kind!r}{v} page={','.join(map(str, p.pages))} pins={p.pin_count}")
    out.append("")
    for n in circuit.nets:
        rail = " [rail]" if n.is_rail else ""
        alias = f" aliases={','.join(n.aliases[1:])}" if len(n.aliases) > 1 else ""
        flags = f" unnamed_flags={n.flags}" if n.flags else ""
        out.append(f"NET {n.name}{rail} pins={len(n.pins)}{alias}{flags}")
        if n.pins:
            out.append("  " + "  ".join(f"{r}.{p or '?'}" + (f"/{nm}" if nm else "") for r, p, nm in n.pins))
    out.append("")
    return "\n".join(out)


def write_json_netlist(circuit: Circuit, title: str) -> str:
    doc = {
        "title": title,
        "source": circuit.source,
        "generator": "SchematicNetlist",
        "pages": [{"page": p, "source": circuit.page_source[p]} for p in circuit.pages],
        "parts": [
            {
                "refdes": p.refdes, "kind": p.kind, "value": p.value, "pages": p.pages, "group": p.group,
                "pins": [{"number": q.number, "name": q.name, "net": q.net, "page": q.page} for q in p.pins],
                "notes": p.notes,
            }
            for p in circuit.parts
        ],
        "nets": [
            {
                "name": n.name, "aliases": n.aliases, "rail": n.is_rail, "rail_reason": n.rail_reason,
                "pages": n.pages, "unnamed_flags": n.flags,
                "pins": [{"refdes": r, "number": p, "name": nm} for r, p, nm in n.pins],
            }
            for n in circuit.nets
        ],
        "warnings": [asdict(w) for w in circuit.warnings],
        "log": circuit.log,
    }
    return json.dumps(doc, indent=1, ensure_ascii=False)
